
# Task 1: Plotting with Pandas
import sqlite3
import pandas as pd
import matplotlib.pyplot as plt

try:
    with  sqlite3.connect('../db/lesson.db') as conn:
        print("Database created and connected successfully.")
        cursor = conn.cursor()

        sql_statement = """
        SELECT last_name,
            SUM(price * quantity) AS revenue
        FROM employees e 
        JOIN orders o 
            ON e.employee_id = o.employee_id 
        JOIN line_items l 
            ON o.order_id = l.order_id
        JOIN products p
            ON l.product_id = p.product_id
        GROUP BY e.employee_id;
        """

        employee_results = pd.read_sql_query(sql_statement, conn)
        print(employee_results)

        # Bar plot
        employee_results.plot(x="last_name", y="revenue", kind="bar", color="skyblue", title="Revenue generated by Employees")
        plt.xlabel("Employee Last Name")
        plt.ylabel("Revenue ($)")
        plt.show()

except sqlite3.Error as e:
    print(f"An error occurred: {e}")

